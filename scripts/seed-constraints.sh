#!/usr/bin/env bash
# Seed fictitious employee constraints for testing.
# Run AFTER creating the employee_constraints table in Supabase.
# Usage: bash scripts/seed-constraints.sh

BASE="http://localhost:3000/api/employee-constraints"

post() {
  local emp=$1 date=$2 type=$3 note=$4
  local result
  result=$(curl -s -X POST "$BASE" \
    -H "Content-Type: application/json" \
    -d "{\"employeeId\":\"$emp\",\"employeeName\":\"$emp\",\"dateISO\":\"$date\",\"constraintType\":\"$type\",\"note\":\"$note\"}")
  if echo "$result" | grep -q '"error"'; then
    echo "✗  $emp  $date — $(echo "$result" | grep -o '"error":"[^"]*"')"
  else
    echo "✓  $emp  $date  ($type)"
  fi
}

